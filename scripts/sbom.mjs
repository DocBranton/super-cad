// Regenerate the software bill of materials and its human-readable summary.
//   npm run sbom
// Outputs (docs/compliance/):
//   sbom-runtime.cdx.json  CycloneDX 1.6, everything that runs in production (server + browser)
//   sbom-full.cdx.json     CycloneDX 1.6, including build-only tools
//   SBOM.md                summary: where each component runs, licence, vulnerability audit
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { build } from "vite";

const out = "docs/compliance";
mkdirSync(out, { recursive: true });
const sh = (cmd, args) => execFileSync(cmd, args, { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
const cdx = (file, extra = []) =>
  sh("npx", ["--no-install", "cyclonedx-npm", ...extra, "--output-format", "JSON", "--spec-version", "1.6", "--output-reproducible", "--output-file", `${out}/${file}`]);
cdx("sbom-runtime.cdx.json", ["--omit", "dev"]);
cdx("sbom-full.cdx.json");

// Which packages are actually compiled into the browser bundle (main thread + geometry worker)?
const client = new Set();
const collect = {
  name: "collect-packages",
  generateBundle() {
    for (const id of this.getModuleIds()) {
      const m = /node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(id);
      if (m) client.add(m[1]);
    }
  },
};
await build({ logLevel: "silent", build: { write: false }, plugins: [collect], worker: { format: "es", plugins: () => [collect] } });

// Which packages does the Node server load? The production tree of its direct dependencies.
// `npm ls --all` prints each package's subtree once and marks repeats as deduped, so collect
// every subtree by name first, then walk from the server's direct dependencies.
const server = new Set();
const tree = JSON.parse(sh("npm", ["ls", "--omit", "dev", "--all", "--json"]));
const subtrees = new Map();
const index = (deps = {}) =>
  Object.entries(deps).forEach(([n, d]) => {
    if (d.dependencies && Object.keys(d.dependencies).length) subtrees.set(n, d.dependencies);
    index(d.dependencies);
  });
index(tree.dependencies);
const visit = (n) => {
  if (server.has(n)) return;
  server.add(n);
  Object.keys(subtrees.get(n) ?? {}).forEach(visit);
};
["express", "zod"].forEach(visit);

const audit = JSON.parse(execFileSync("npm", ["audit", "--omit=dev", "--json"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).toString() || "{}");
const vulns = audit.metadata?.vulnerabilities ?? {};

const sbom = JSON.parse(readFileSync(`${out}/sbom-runtime.cdx.json`, "utf8"));
const full = JSON.parse(readFileSync(`${out}/sbom-full.cdx.json`, "utf8"));
const lic = (c) => (c.licenses ?? []).map((l) => l.license?.id ?? l.license?.name ?? l.expression).filter(Boolean).join(" OR ") || "UNKNOWN";
const nameOf = (c) => (c.group ? `${c.group}/${c.name}` : c.name);
const rows = sbom.components
  .map((c) => ({ name: nameOf(c), version: c.version, license: lic(c), where: [client.has(nameOf(c)) && "browser", server.has(nameOf(c)) && "server"].filter(Boolean).join(" + ") || "installed, not loaded" }))
  .sort((a, b) => (a.where === b.where ? a.name.localeCompare(b.name) : a.where.localeCompare(b.where)));
const byLicense = rows.reduce((m, r) => ((m[r.license] = (m[r.license] ?? 0) + 1), m), {});
const pkg = JSON.parse(readFileSync("package.json", "utf8"));

const md = `# Software bill of materials — ${pkg.name} ${pkg.version}

Generated by \`npm run sbom\` on ${new Date().toISOString().slice(0, 10)} from \`package-lock.json\`. Machine-readable SBOMs (CycloneDX 1.6):

- [\`sbom-runtime.cdx.json\`](sbom-runtime.cdx.json) — ${sbom.components.length} components that run in production
- [\`sbom-full.cdx.json\`](sbom-full.cdx.json) — ${full.components.length} components including build-only tools (Vite, TypeScript, type definitions)

## Summary

| | |
|---|---|
| Runtime components | ${sbom.components.length} (${client.size} in the browser bundle, ${server.size} loaded by the server) |
| Known vulnerabilities (\`npm audit --omit=dev\`) | critical ${vulns.critical ?? 0} · high ${vulns.high ?? 0} · moderate ${vulns.moderate ?? 0} · low ${vulns.low ?? 0} |
| Licences | ${Object.entries(byLicense).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ")} |
| Copyleft components | ${rows.filter((r) => /GPL/i.test(r.license)).map((r) => `${r.name} ${r.version} — ${r.license}`).join("; ") || "none"} |

## Bundled native code

The browser bundle includes one large compiled component that the npm metadata describes only as a package:

| Component | Delivered as | Licence | Notes |
|---|---|---|---|
| Open CASCADE Technology (geometry kernel), compiled to WebAssembly by opencascade.js, packaged as \`replicad-opencascadejs\` | \`dist/assets/replicad_single-*.wasm\` (≈23 MB; 5.5 MB Brotli) | LGPL-2.1 | Separate, replaceable file loaded at runtime. The kernel version is not exposed by the build; confirm it from the package's build configuration before submission. |

Vite also inlines a few lines of its own runtime helpers (module preload) into the bundle; Vite is MIT-licensed and listed in the full SBOM.

## Runtime components

| Package | Version | Licence | Runs in |
|---|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.where} |`).join("\n")}

"Installed, not loaded" packages are pulled in by the dependency tree (mostly type definitions and optional peers) but are not part of the browser bundle or the server's module graph.
`;
writeFileSync(`${out}/SBOM.md`, md);
console.log(`SBOM: ${sbom.components.length} runtime / ${full.components.length} total; browser ${client.size}, server ${server.size}; vulns ${JSON.stringify(vulns)}`);
